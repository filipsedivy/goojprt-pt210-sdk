"""Generate a receipt template with random shopping items.

Writes a TOML template (see ``examples/``) for ``goojprt --template``: a header,
one table row per item (name, pieces, price), the total and a footer. The
items, quantities and prices are random; ``--seed`` makes a receipt
reproducible, and the seed is recorded in the file.

    python scripts/random_receipt.py                     # 25 items to examples/shopping-receipt.toml
    python scripts/random_receipt.py --items 12 --seed 7 --out my.toml
    goojprt <address> --template examples/shopping-receipt.toml

Rows are bitmap text, so Czech diacritics print correctly on any unit.
"""

import argparse
import random
import sys
from pathlib import Path

#: Grocery items with a typical price in CZK per piece. Names fit the item column.
PRODUCTS: tuple[tuple[str, float], ...] = (
    ("Rohlík", 3.9), ("Chléb konzumní", 36.9), ("Máslo 250 g", 62.9), ("Mléko 1 l", 21.9),
    ("Vejce 10 ks", 58.9), ("Jogurt bílý", 12.9), ("Sýr Eidam 100 g", 28.9), ("Šunka 100 g", 34.9),
    ("Salám Vysočina", 44.9), ("Okurka salátová", 19.9), ("Rajčata 500 g", 39.9), ("Paprika červená", 14.9),
    ("Brambory 2 kg", 49.9), ("Cibule 1 kg", 24.9), ("Jablka 1 kg", 32.9), ("Banány 1 kg", 29.9),
    ("Pomeranče 1 kg", 34.9), ("Citron", 7.9), ("Mrkev 1 kg", 22.9), ("Zelí bílé", 18.9),
    ("Těstoviny 500 g", 27.9), ("Rýže 1 kg", 46.9), ("Mouka hladká", 19.9), ("Cukr krystal", 24.9),
    ("Olej slunečnicový", 54.9), ("Káva mletá 250 g", 89.9), ("Čaj černý", 42.9), ("Čokoláda mléčná", 25.9),
    ("Sušenky Opavia", 21.9), ("Müsli tyčinka", 11.9), ("Pivo Gambrinus", 17.9), ("Minerálka 1,5 l", 18.9),
    ("Džus pomeranč", 33.9), ("Kečup jemný", 36.9), ("Hořčice plnotučná", 19.9), ("Majonéza", 31.9),
    ("Toaletní papír", 79.9), ("Mýdlo tekuté", 49.9), ("Prací gel", 129.9), ("Houbičky na nádobí", 22.9),
    ("Zubní pasta", 59.9), ("Šampon", 69.9), ("Sáčky na odpad", 34.9), ("Ubrousky", 27.9),
    ("Kuřecí prsa 500 g", 79.9), ("Mleté maso 500 g", 84.9), ("Uzená makrela", 64.9), ("Tvaroh měkký", 23.9),
    ("Smetana 33 %", 39.9), ("Rohlíky tukové", 4.9),
)

#: Longest item name that fits the first table column at the default font size.
MAX_NAME_LENGTH = 18


def czk(cents: int) -> str:
    """``12990`` -> ``"129,90"`` (Czech decimal comma, space as thousands separator)."""
    whole, fraction = divmod(cents, 100)
    return f"{whole:,}".replace(",", " ") + f",{fraction:02d}"


def choose_rows(rng: random.Random, count: int) -> list[tuple[str, int, int]]:
    """``count`` distinct random products as ``(name, pieces, line total in cents)``.

    :raises ValueError: When ``count`` is not between 1 and the number of products.
    """
    if not 1 <= count <= len(PRODUCTS):
        raise ValueError(f"items must be between 1 and {len(PRODUCTS)}")
    rows: list[tuple[str, int, int]] = []
    for name, base_price in rng.sample(PRODUCTS, count):
        unit_cents = round(base_price * rng.uniform(0.85, 1.15) * 10) * 10      # whole 10 haléř steps
        pieces = rng.choices([1, 2, 3, 4, 5, 6], weights=[50, 25, 10, 8, 4, 3])[0]
        rows.append((name, pieces, unit_cents * pieces))
    return rows


def build_receipt(count: int, seed: int) -> tuple[str, int]:
    """Return the template text and the total in cents.

    :raises ValueError: When ``count`` is not between 1 and the number of products.
    """
    rows = choose_rows(random.Random(seed), count)
    total = sum(line for _, _, line in rows)
    pieces_total = sum(pieces for _, pieces, _ in rows)

    out = [
        f"# Random shopping receipt: {count} items, generated by scripts/random_receipt.py --seed {seed}",
        "# Columns: item | pieces (ks) | price in CZK. Print it with:",
        "#   goojprt <address> --template examples/shopping-receipt.toml",
        "",
        toml_item('type = "text_image"', 'text = "Potraviny U Nováků"', "font_size = 30", 'align = "center"'),
        toml_item('type = "text_image"', 'text = "Dlouhá 12, Praha 1\\nIČ 12345678"', "font_size = 18",
              'align = "center"', "padding = 2"),
        toml_item('type = "text"', 'text = "{{datetime}}"', 'align = "center"'),
        toml_item('type = "line"'),
        toml_row("Položka", "ks", "Cena", font_size=20),
        toml_item('type = "line"'),
    ]
    out += [toml_row(name, str(pieces), czk(line)) for name, pieces, line in rows]
    out += [
        toml_item('type = "line"'),
        toml_row(f"Položek: {count}", str(pieces_total), "", font_size=20),
        toml_item('type = "text_image"', f'text = "CELKEM  {czk(total)} Kč"', "font_size = 30",
              'align = "right"', "padding = 6"),
        toml_item('type = "line"'),
        toml_item('type = "text_image"', 'text = "Děkujeme za nákup!"', "font_size = 22",
              'align = "center"'),
        toml_item('type = "feed"', "lines = 4"),
    ]
    return "\n".join(out) + "\n", total


def toml_item(*lines: str) -> str:
    """One ``[[items]]`` table of a template."""
    return "[[items]]\n" + "\n".join(lines) + "\n"


def toml_row(name: str, pieces: str, price: str, font_size: int = 20) -> str:
    """A three-column table row: item, pieces, price."""
    if len(name) > MAX_NAME_LENGTH + 4:                 # header / summary rows may be a bit longer
        raise ValueError(f"item name too long for the column: {name!r}")
    return toml_item(
        'type = "grid"', f"font_size = {font_size}", "padding = 3",
        "columns = [",
        f'  {{ width = 58, align = "left",  text = "{name}" }},',
        f'  {{ width = 12, align = "right", text = "{pieces}" }},',
        f'  {{ width = 30, align = "right", text = "{price}" }},',
        "]",
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--items", type=int, default=25, help="number of items (default: 25)")
    parser.add_argument("--seed", type=int, default=None, help="random seed (default: a fresh one)")
    parser.add_argument("--out", type=Path, default=Path(__file__).resolve().parent.parent
                        / "examples" / "shopping-receipt.toml",
                        help="output file, or - for stdout (default: examples/shopping-receipt.toml)")
    args = parser.parse_args(argv)

    seed = args.seed if args.seed is not None else random.SystemRandom().randrange(1, 1_000_000)
    try:
        text, total = build_receipt(args.items, seed)
    except ValueError as exc:
        parser.error(str(exc))
    if str(args.out) == "-":
        sys.stdout.write(text)
    else:
        args.out.write_text(text, encoding="utf-8")
        print(f"{args.items} items, total {czk(total)} Kč (seed {seed}) -> {args.out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
